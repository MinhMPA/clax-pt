"""The committed CLASS RECFAST (recfast_Heswitch=1) thermodynamics references
used by the recombination-staging tests (smsharma/clax#48) exist, are
physically sane, and were made for the cosmologies the tests build. Generated by
scripts/generate_class_reference.py --recfast-hesw1-thermo in the classpt env
(CLASS-PT build, CLASS v3.3.4) at tol_thermo_integration = 1e-10; stock CLASS 3.3.4
(PyPI classy) reproduces all 11 to <= 2.9e-8 in x_e and <= 2.1e-10 in T_b
(scripts/crosscheck_recfast_hesw1_stock.py, Oct 19, 2026). At CLASS's default
tolerance 1e-6 the two builds differed by up to 7.1e-6 (2.3e-4 at omega_b - 20%),
CLASS's own integration error, not a physics difference."""
import importlib.util
import json
import os

import numpy as np
import pytest

from tests.conftest import COSMOLOGY_GRID_RECOMB, NEFF_NCDM

REF = os.path.join(os.path.dirname(__file__), "..", "reference_data")
NOT4 = 3.9715  # CLASS thermodynamics.h:707


def test_reference_grid_matches_test_grid():
    """The generator's RECOMB_GRID (names and overrides the references were made
    with) equals tests/conftest.py COSMOLOGY_GRID_RECOMB (what the tests build under
    the same names); a change on one side only would silently pair a reference
    with a different cosmology. Cosmology-independent bookkeeping: exempt from the
    multi-cosmology rule."""
    path = os.path.join(os.path.dirname(__file__), "..", "scripts", "generate_class_reference.py")
    spec = importlib.util.spec_from_file_location("_generate_class_reference", path)
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    assert gen.NEFF_NCDM == NEFF_NCDM, f"ERROR NEFF_NCDM differs: {gen.NEFF_NCDM} vs {NEFF_NCDM}"
    diff = sorted(k for k in set(gen.RECOMB_GRID) | set(COSMOLOGY_GRID_RECOMB)
                  if gen.RECOMB_GRID.get(k) != COSMOLOGY_GRID_RECOMB.get(k))
    assert not diff, f"ERROR generator RECOMB_GRID and conftest COSMOLOGY_GRID_RECOMB differ at {diff}"


@pytest.mark.parametrize("name", list(COSMOLOGY_GRID_RECOMB))
def test_recfast_hesw1_reference_is_sane(name):
    path = os.path.join(REF, name, "thermo_recfast_hesw1.npz")
    assert os.path.isfile(path), f"ERROR missing {path}"
    d = np.load(path)
    z, xe, g = d["z"], d["x_e"], d["g"]
    assert z.size == 4000 and np.all(np.diff(z) > 0), \
        f"ERROR {name}: z grid has {z.size} points (want 4000) or is not increasing"
    assert np.all(np.isfinite(xe)) and np.all(xe > 0), f"ERROR {name}: x_e not finite and positive"
    with open(path.replace(".npz", ".json")) as fh:
        prov = json.load(fh)
    yhe = prov["class_params"]["YHe"]
    f_he = yhe / (NOT4 * (1.0 - yhe))
    assert abs(xe[-1] - (1.0 + 2.0 * f_he)) < 1e-2, \
        f"ERROR {name}: x_e(z=8000) = {xe[-1]:.5f}, fully ionised value {1 + 2 * f_he:.5f}"   # H, He fully ionised
    assert xe[np.argmin(np.abs(z - 500.0))] < 0.05, \
        f"ERROR {name}: x_e(z=500) = {xe[np.argmin(np.abs(z - 500.0))]:.4f}, not recombined"   # recombined by z = 500
    zp = z[np.argmax(g)]
    assert 1040.0 < zp < 1120.0, f"ERROR {name}: visibility peak at z = {zp:.1f}, outside 1040-1120"   # visibility peak
    print(f"{name}: x_e(8000)={xe[-1]:.5f} peak z={zp:.1f} YHe={yhe}")
